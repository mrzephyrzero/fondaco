"""Discovery output: the annotation proposal, as JSON, YAML, or Postgres SQL.

The JSON form is also what the Postgres adapter reads as an annotation
overlay (`FONDACO_SCHEMA_ANNOTATIONS`) once a Data Owner has reviewed it.
YAML is written without a YAML library: every scalar is emitted as a JSON
string/number/null, which is valid YAML.
"""

from __future__ import annotations

import json

from executor.discovery.classifier import TableFinding

FORMAT_VERSION = 1


def to_dict(findings: list[TableFinding]) -> dict:
    return {
        "format": "fondaco-annotations",
        "version": FORMAT_VERSION,
        "review_required": True,
        "note": (
            "Generated by `fondaco discover` from a local sample. A proposal: the Data "
            "Owner confirms every label before it is applied. Discovery never proposes "
            "'public'."
        ),
        "tables": [
            {
                "name": t.name,
                "label": t.label,
                "source": t.source,
                "sampled_rows": t.sampled_rows,
                "notes": list(t.notes),
                "columns": [
                    {
                        "name": c.name,
                        "type": c.sql_type,
                        "label": c.label,
                        "reasons": list(c.reasons),
                        "enum_values": list(c.enum_values) if c.enum_values else None,
                        "business_description": None,
                    }
                    for c in t.columns
                ],
            }
            for t in findings
        ],
    }


def to_json(findings: list[TableFinding]) -> str:
    return json.dumps(to_dict(findings), indent=2, ensure_ascii=False) + "\n"


def _yaml(value: object, indent: int) -> list[str]:
    pad = "  " * indent
    if isinstance(value, dict):
        lines = []
        for key, item in value.items():
            if isinstance(item, dict | list) and item:
                lines.append(f"{pad}{json.dumps(key)}:")
                lines.extend(_yaml(item, indent + 1))
            else:
                lines.append(f"{pad}{json.dumps(key)}: {_scalar(item)}")
        return lines
    if isinstance(value, list):
        lines = []
        for item in value:
            if isinstance(item, dict | list) and item:
                nested = _yaml(item, indent + 1)
                lines.append(f"{pad}- {nested[0].strip()}")
                lines.extend(nested[1:])
            else:
                lines.append(f"{pad}- {_scalar(item)}")
        return lines
    return [f"{pad}{_scalar(value)}"]


def _scalar(value: object) -> str:
    if isinstance(value, dict):
        return "{}"
    if isinstance(value, list):
        return "[]"
    return json.dumps(value, ensure_ascii=False)


def to_yaml(findings: list[TableFinding]) -> str:
    return "\n".join(_yaml(to_dict(findings), 0)) + "\n"


def _literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def to_sql_comments(findings: list[TableFinding], schema: str = "public") -> str:
    """`COMMENT ON` statements in the `label:<level> <description>` form the
    Postgres adapter reads. For review and manual application only."""
    lines = [
        "-- Generated by `fondaco discover`. REVIEW BEFORE APPLYING: every label is a",
        "-- proposal. Applying this replaces existing comments on these objects.",
        "BEGIN;",
    ]
    for table in findings:
        target = f"{_ident(schema)}.{_ident(table.name)}"
        lines.append(
            f"COMMENT ON TABLE {target} IS {_literal(f'label:{table.label} (discovered)')};"
        )
        for column in table.columns:
            why = ", ".join(column.reasons)
            comment = f"label:{column.label} (discovered: {why})"
            lines.append(
                f"COMMENT ON COLUMN {target}.{_ident(column.name)} IS {_literal(comment)};"
            )
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"
